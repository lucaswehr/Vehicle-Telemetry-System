#!/usr/bin/env python3
"""Build the firmware's offline city table from a GeoNames dump (citiesNNNN.txt).

  1. Download cities5000.zip from https://download.geonames.org/export/dump/ and unzip it.
  2. python tools/make_places.py tools/data/cities5000.txt
     (writes lib/places/places_data.cpp; open the summary it prints to see the flash cost)

Keeps only the chosen country (default US) and places with at least --min-pop people. Names use the
plain-ASCII spelling so the screen font can draw them. Coordinates are stored in hundredths of a degree
(about 1.1 km), which is plenty for "which town am I in".

GeoNames columns used (tab separated): 1 name, 2 asciiname, 4 latitude, 5 longitude, 6 feature class,
8 country code, 10 admin1 code (the state, for the US), 14 population.
"""
import argparse
import os
import sys

NAME_MAX = 23          # DashInput.city holds 23 characters plus the terminator


def c_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def read_places(path, country, min_pop):
    out, skipped = [], 0
    with open(path, encoding="utf-8") as f:
        for line in f:
            cols = line.rstrip("\n").split("\t")
            if len(cols) < 15:
                skipped += 1
                continue
            if cols[8] != country or cols[6] != "P":
                continue
            try:
                pop = int(cols[14] or 0)
                lat, lon = float(cols[4]), float(cols[5])
            except ValueError:
                skipped += 1
                continue
            if pop < min_pop:
                continue
            name = (cols[2] or cols[1]).strip()
            state = cols[10].strip()
            if not name:
                continue
            name = name[:NAME_MAX]
            if len(state) > 2 or not state.isalpha():
                state = ""      # numeric admin codes (other countries) are not useful on screen
            out.append((round(lat * 100), round(lon * 100), name, state.upper(), pop))
    return out, skipped


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("geonames_file")
    ap.add_argument("--country", default="US")
    ap.add_argument("--min-pop", type=int, default=5000)
    ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib", "places", "places_data.cpp"))
    args = ap.parse_args()

    places, skipped = read_places(args.geonames_file, args.country, args.min_pop)
    if not places:
        sys.exit("no places found: check the file and --country / --min-pop")
    places.sort(key=lambda p: (p[0], p[1]))        # tidy diffs; the lookup does not rely on order

    seen, unique = set(), []
    for p in places:                                # drop exact duplicates (same name, state and spot)
        key = (p[0], p[1], p[2], p[3])
        if key not in seen:
            seen.add(key)
            unique.append(p)

    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// GENERATED by tools/make_places.py from a GeoNames dump. Do not edit by hand.\n")
        f.write(f"// {len(unique)} places in {args.country} with at least {args.min_pop} people.\n")
        f.write('#include "places.h"\n\n')
        f.write("const PlaceEntry PLACES[] = {\n")
        for lat, lon, name, state, pop in unique:
            f.write(f"  {{{lat}, {lon}, {c_string(name)}, {c_string(state)}}},\n")
        f.write("};\n")
        f.write("const size_t PLACES_COUNT = sizeof(PLACES) / sizeof(PLACES[0]);\n")

    nbytes = sum(8 + len(p[2]) + 1 + len(p[3]) + 1 for p in unique)
    print(f"wrote {len(unique)} places to {os.path.relpath(args.out)} "
          f"(about {nbytes / 1024:.0f} KB of flash){'; skipped %d malformed lines' % skipped if skipped else ''}")


if __name__ == "__main__":
    main()
